using Remedy.Framework;
using Remedy.Schematics;
using System.Collections.Generic;
using UnityEngine;
using UnityEngine.SceneManagement;

/// <summary>
/// Creates a Schematic Object for every registered <see cref="SingletonGraph"/> before the first scene loads, keeps it
/// across scenes (DontDestroyOnLoad), gives it the graph's State Machine when it has one, and forwards the
/// game-wide events (scene loads, runtime updates) to its graph.
/// </summary>
public static class SingletonGraphSpawner
{
    private static readonly List<SchematicObject> _spawned = new();
    private static bool _sceneEventsHooked;

    /// <summary>The Singleton objects created this session, in creation order.</summary>
    public static IReadOnlyList<SchematicObject> Spawned => _spawned;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]
    private static void ResetStatics()
    {
        _spawned.Clear();
        _sceneEventsHooked = false;
    }

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
    private static void SpawnAll()
    {
        var graphs = new List<SingletonGraph>();
        foreach (var graph in SchematicManagerData.SingletonGraphs)
            if (graph != null && graph.SpawnOnStart && !graphs.Contains(graph))
                graphs.Add(graph);
        graphs.Sort((a, b) => a.Order.CompareTo(b.Order));

        foreach (var graph in graphs)
            Spawn(graph);

        foreach (var host in _spawned)
            host.SchematicGraph.TriggerEvent<OnBeforeFirstSceneLoaded>(host.gameObject);

        HookSceneEvents();
    }

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
    private static void AfterFirstScene()
    {
        foreach (var host in _spawned)
            if (host != null)
                host.SchematicGraph.TriggerEvent<OnAfterFirstSceneLoaded>(host.gameObject);
    }

    /// <summary>
    /// Creates the object for a Singleton Graph (if it doesn't exist yet) and returns it. Also usable for Singletons
    /// whose "Spawn On Start" is off.
    /// </summary>
    public static SchematicObject Spawn(SingletonGraph graph)
    {
        if (graph == null)
            return null;
        if (graph.Host != null)
            return graph.Host;

        // Built inactive, so the object registers (and its Behaviors spawn) only once everything is set up.
        var gameObject = new GameObject("[Singleton] " + graph.name);
        gameObject.SetActive(false);
        Object.DontDestroyOnLoad(gameObject);

        var schematic = gameObject.AddComponent<SchematicObject>();
        schematic.SchematicGraph = graph;
        // Singletons have no prefab: they're identified by their graph.
        schematic.AssignObjectID(SchematicObject.ObjectIDFor("singleton:" + graph.name));

        if (graph.StateMachine != null)
        {
            var attachment = new BehaviorAttachment { Metadata = MetadataFor(typeof(StateMachine)) };
            attachment.SetOverride("Definition", graph.StateMachine, typeof(StateMachineDefinition));
            var list = new BehaviorAttachmentList();
            list.Items.Add(attachment);
            schematic.Behaviors[gameObject] = list;
        }

        gameObject.AddComponent<SingletonGraphHost>();
        SingletonGraph.SetHost(graph, schematic);
        _spawned.Add(schematic);

        gameObject.SetActive(true);
        // The game itself: it hears every player's input, whoever possesses what.
        Possession.HearEveryController(schematic);
        return schematic;
    }

    // Metadata is normally generated by the editor; one made on the spot works too (code defaults, no overrides).
    private static BehaviorMetadata MetadataFor(System.Type type)
    {
        var metadata = BehaviorMetadata.Get(type);
        if (metadata != null)
            return metadata;
        metadata = ScriptableObject.CreateInstance<BehaviorMetadata>();
        metadata.BehaviorType = type;
        metadata.hideFlags = HideFlags.DontSave;
        return metadata;
    }

    private static void HookSceneEvents()
    {
        if (_sceneEventsHooked)
            return;
        _sceneEventsHooked = true;

        SceneManager.sceneLoaded += (scene, mode) => ForEach(host => host.SchematicGraph.TriggerEvent<OnSceneLoaded>(host.gameObject, scene));
        SceneManager.sceneUnloaded += scene => ForEach(host => host.SchematicGraph.TriggerEvent<OnSceneUnloaded>(host.gameObject, scene));
        SceneManager.activeSceneChanged += (previous, next) => ForEach(host => host.SchematicGraph.TriggerEvent<OnActiveSceneChanged>(host.gameObject, previous, next));
    }

    private static void ForEach(System.Action<SchematicObject> action)
    {
        for (int i = 0; i < _spawned.Count; i++)
            if (_spawned[i] != null && _spawned[i].SchematicGraph != null)
                action(_spawned[i]);
    }
}
